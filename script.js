const audio =
    $("#audio");

const musicPlayer =
    $("#musicPlayer");

const musicName =
    $("#musicName");

const musicCover =
    $("#musicCover");

let currentMusic = 0;


function loadMusic(index) {

    const music =
        CONFIG.music[index];

    audio.src =
        music.file;

    musicName.textContent =
        music.name;

    musicCover.src =
        music.cover;

}


function playCurrentMusic() {

    loadMusic(currentMusic);

    audio.play()
        .catch(() => {});

    musicPlayer.classList.add("show");

    $("#playMusic").textContent =
        "❚❚";

}


function pauseMusic() {

    audio.pause();

    $("#playMusic").textContent =
        "▶";

}


$("#musicButton").onclick = () => {

    musicPlayer.classList.add("show");

    if (audio.paused) {

        playCurrentMusic();

    }

};


$("#playMusic").onclick = () => {

    if (audio.paused) {

        playCurrentMusic();

    } else {

        pauseMusic();

    }

};


$("#nextMusic").onclick = () => {

    currentMusic++;

    if (
        currentMusic >=
        CONFIG.music.length
    )
        currentMusic = 0;

    playCurrentMusic();

};


$("#prevMusic").onclick = () => {

    currentMusic--;

    if (currentMusic < 0)
        currentMusic =
            CONFIG.music.length - 1;

    playCurrentMusic();

};


$("#closeMusic").onclick = () => {

    musicPlayer.classList.remove("show");

};


audio.onended = () => {

    currentMusic++;

    if (
        currentMusic >=
        CONFIG.music.length
    )
        currentMusic = 0;

    playCurrentMusic();

};


